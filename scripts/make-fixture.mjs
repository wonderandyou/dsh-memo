/**
 * 生成预览用 fixture：从真实 MEMO.md 取数据，写成 preview/fixture.js。
 * 只用于无头预览页（preview/index.html），不进插件运行时。
 *
 * 用法： node scripts/make-fixture.mjs
 */

import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { createMemo } from '../lib/memo-core.js'

const MEMO = path.join(os.homedir(), '.dsh', 'MEMO.md')
const memo = createMemo(MEMO)
const info = memo.info()
const outline = memo.outline({ depth: 2 })

// 从 outline 解析出结构化目录（与 host 的 listSections 同形）
const sections = []
for (const line of outline.text.split('\n')) {
  const m = /^\s*§(\S+)\s+(.+?)\s+—\s+L(\d+)-(\d+),\s+([\d,]+)\s+chars\s+\(~(?:[\d,]+)\s+tok\)$/u.exec(line)
  if (m === null) continue
  sections.push({
    id: m[1],
    title: m[2],
    level: line.startsWith('  §') ? 3 : 2,
    start: Number(m[3]),
    end: Number(m[4]),
    chars: Number(m[5].replace(/,/g, '')),
  })
}

const now = Date.now()
const sample = [
  ['memo_outline', 'depth=2', 2683, 838, 97, true, ''],
  ['memo_quick', 'ports', 929, 290, 99, true, '0.2'],
  ['memo_search', '8199', 533, 167, 99, true, '0.2'],
  ['memo_project', 'qq', 7857, 2455, 92, true, '3.6'],
  ['memo_section', '3.13', 4200, 1313, 96, true, '3.13'],
  ['memo_playbook', 'download', 508, 159, 99, true, '5'],
  ['memo_status', '', 1368, 428, 99, true, '6'],
  ['memo_search', 'NARB_DISABLE_NATIVE_CACHE', 412, 129, 100, true, '3.15'],
  ['memo_project', 'zzz', 0, 0, 0, false, ''],
]
const log = sample.map((row, i) => ({
  t: now - (sample.length - i) * 47000,
  tool: row[0],
  arg: row[1],
  chars: row[2],
  tokens: row[3],
  savedPct: row[4],
  ok: row[5],
  section: row[6],
  hits: row[0] === 'memo_search' ? 3 : 0,
})).reverse()

const fixture = {
  info,
  sections,
  stats: { calls: log.length, chars: log.reduce((a, r) => a + r.chars, 0), tokens: 0, errors: 1, uptimeSec: 5320 },
  log,
  detail: {
    '0.2': memo.section('0.2').text,
    '3.6': memo.section('3.6').text,
  },
  search: {
    '8199': memo.search('8199').text,
    'port': memo.search('port').text,
  },
}

const out = path.join(import.meta.dirname, 'preview', 'fixture.js')
fs.writeFileSync(out, '/* generated by scripts/make-fixture.mjs — do not edit */\nwindow.__FIXTURE = '
  + JSON.stringify(fixture, null, 2) + '\n', 'utf8')
console.log('wrote ' + out + ' (' + fs.statSync(out).size + ' bytes, ' + sections.length + ' sections)')
